// Pipeline conseil municipal — ÉTAPE 4 : ouvrir (ou mettre à jour) la PR
// **draft** portant la fusion. Voir ADR-0053, calqué sur create-veille-pr.js.
//
// Le draft n'est pas un détail : un texte déduit de PDF n'entre jamais dans
// `main` sans qu'un humain l'ait relu et sorti du brouillon lui-même
// (ADR-0023). Une seule PR vivante : la branche est fixe, un nouveau run la
// met à jour au lieu d'empiler des PR (même règle que l'issue liens-morts).
//
// ⚠️ Une PR créée avec le GITHUB_TOKEN ne déclenche AUCUN workflow : pas de
// coche verte (ADR-0023). Les contrôles (validation, anti-doublon, contrôle
// CI rejoué) sont exécutés DANS le run qui pousse — le corps de PR y renvoie.
//
// Le corps inclut `conseil-drive/resume-pr.md`, produit par la fusion. Sa
// part venue de l'agent (raisons d'écartement) y a été TRONQUÉE et traitée
// comme du texte — jamais comme des instructions.
//
// Env : GITHUB_TOKEN, GITHUB_REPOSITORY, GITHUB_RUN_URL, CONSEIL_PR_BRANCH,
//       CONSEIL_PR_BASE (défaut main). Node 20+, aucune dépendance.

'use strict';

const fs = require('node:fs');
const path = require('node:path');

const RACINE = path.resolve(__dirname, '..');
const GITHUB_TOKEN = process.env.GITHUB_TOKEN;
const REPO = process.env.GITHUB_REPOSITORY || '';
const API = (process.env.GITHUB_API_URL || 'https://api.github.com').replace(/\/$/, '');
const BRANCHE = (process.env.CONSEIL_PR_BRANCH || 'conseil/maj-drive').trim();
const BASE = (process.env.CONSEIL_PR_BASE || 'main').trim();
const RUN_URL = (process.env.GITHUB_RUN_URL || '').trim();

function stop(m, code) { console.error(m); process.exit(code); }
if (!GITHUB_TOKEN || !REPO.includes('/')) stop('GITHUB_TOKEN ou GITHUB_REPOSITORY manquant.', 1);

async function gh(methode, chemin, corps) {
  const rep = await fetch(API + chemin, {
    method: methode,
    headers: {
      Authorization: 'Bearer ' + GITHUB_TOKEN,
      Accept: 'application/vnd.github+json',
      'User-Agent': 'mat-conseil-drive',
      ...(corps ? { 'Content-Type': 'application/json' } : {})
    },
    body: corps ? JSON.stringify(corps) : undefined
  });
  const json = await rep.json().catch(() => ({}));
  if (!rep.ok) throw new Error(methode + ' ' + chemin + ' → HTTP ' + rep.status + ' ' + (json.message || ''));
  return json;
}

const chResume = path.join(RACINE, process.env.CONSEIL_DRIVE_DIR || 'conseil-drive', 'resume-pr.md');
const resume = fs.existsSync(chResume) ? fs.readFileSync(chResume, 'utf8').slice(0, 20000) : '_Résumé indisponible._';

const corps = [
  'Compte(s) rendu(s) relevé(s) sur le Drive de la mairie, résumés « en clair » et fusionnés dans',
  '`data/conseil.json` par `scripts/conseil-drive-fusion.js` (règles anti-doublon vérifiées par',
  '`scripts/check-conseil-drive.js`). Voir **ADR-0053**.',
  '',
  '> ⚠️ **PR ouverte par un workflow : la CI ne se déclenche pas dessus** (`GITHUB_TOKEN`,',
  '> ADR-0023). Les contrôles ont été exécutés dans le run' + (RUN_URL ? ' : ' + RUN_URL : '.'),
  '>',
  '> ✅ **Relire chaque `en_clair` face au PDF avant de sortir la PR du brouillon** —',
  '> ces résumés sont un brouillon d’agent, et seuls les documents officiels font foi.',
  '',
  resume,
  '',
  '---',
  '_Generated by [Claude Code](https://claude.ai/code)_'
].join('\n');

/* ⛔ Premier run réel (26/09) : « HTTP 403 GitHub Actions is not permitted to
   create or approve pull requests » — réglage du dépôt (Settings → Actions →
   General → Workflow permissions), qui bloque AUSSI les PR draft de la veille.
   La branche est déjà poussée : échouer ici sautait l'étape suivante (la
   mémoire des écartés), et la proposition restait invisible. On ne fait donc
   pas échouer le job : avertissement visible + lien pour ouvrir la PR à la
   main, dans le résumé du run. Un silence serait pire qu'un échec. */
function repliSansPR(message) {
  const lien = 'https://github.com/' + REPO + '/compare/' + BASE + '...' + encodeURIComponent(BRANCHE) + '?expand=1';
  console.log('::warning title=Conseil Drive — PR non ouverte::' + message
    + ' — ouvrir la PR à la main : ' + lien
    + ' (ou autoriser « Allow GitHub Actions to create and approve pull requests » dans Settings → Actions → General).');
  if (process.env.GITHUB_STEP_SUMMARY) {
    fs.appendFileSync(process.env.GITHUB_STEP_SUMMARY,
      '\n> ⚠️ **PR non ouverte** : ' + message + '\n>\n> La branche `' + BRANCHE + '` est poussée : '
      + '[ouvrir la PR à la main](' + lien + ').\n> Pour que le robot l’ouvre seul : Settings → Actions → General → '
      + 'Workflow permissions → cocher « Allow GitHub Actions to create and approve pull requests ».\n');
  }
}

(async () => {
  const existantes = await gh('GET', '/repos/' + REPO + '/pulls?state=open&head='
    + encodeURIComponent(REPO.split('/')[0] + ':' + BRANCHE));
  if (existantes.length) {
    const pr = existantes[0];
    await gh('PATCH', '/repos/' + REPO + '/pulls/' + pr.number, { body: corps });
    console.log('PR existante mise à jour : ' + pr.html_url);
    return;
  }
  let pr;
  try {
    pr = await gh('POST', '/repos/' + REPO + '/pulls', {
      title: 'Conseil municipal : mise à jour depuis le Drive (' + new Date().toISOString().slice(0, 10) + ')',
      head: BRANCHE,
      base: BASE,
      draft: true,
      body: corps
    });
  } catch (e) {
    if (/HTTP 403/.test(e.message)) { repliSansPR(e.message); return; }
    throw e;
  }
  console.log('PR draft ouverte : ' + pr.html_url);
})().catch((e) => stop('✗ ' + e.message, 1));
